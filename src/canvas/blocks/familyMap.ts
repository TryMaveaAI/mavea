// here (a few KB of strings) and dynamic-imports just that family's registry chunk. The
// map is hand-maintained — adding a block means adding its line to its family section —
// and tests/family-map.test.ts derives the truth from the real registries, so a missing,
// stale, or misfiled entry fails CI instead of silently rendering nothing.


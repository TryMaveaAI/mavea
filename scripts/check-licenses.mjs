// A few real packages ship an SPDX expression or a missing/odd field that's actually permissive.
// Each entry is a deliberate, reviewed classification — keep this list short and justified.
const OVERRIDES = {
  // The package's bundled LICENSE.md contains the standard MIT grant. Its package.json appends
  // a non-SPDX alternative ("SEE LICENSE IN FEEL-FREE.md"), which the strict parser cannot parse.
  rgbcolor: 'MIT',
};

function spdxOf(pkg) {
  if (OVERRIDES[pkg.name]) return OVERRIDES[pkg.name];
  let l = pkg.license ?? pkg.licenses;
  if (Array.isArray(l))
    l = l
      .map((x) => (typeof x === 'string' ? x : x?.type))
      .filter(Boolean)
      .join(' OR ');
  if (l && typeof l === 'object') l = l.type;
  return typeof l === 'string' ? l.trim() : '';
}

function tokenizeSpdx(expr) {
  const tokens = expr.match(/\(|\)|\bAND\b|\bOR\b|[^\s()]+/gi) ?? [];
  return tokens.map((token) => {
    const upper = token.toUpperCase();
    return upper === 'AND' || upper === 'OR' ? upper : token;
  });
}

// This intentionally supports the part of the SPDX expression grammar used by package.json
// license fields: identifiers, parentheses, AND and OR. WITH exceptions remain a single unknown
// obligation, which is the conservative result until explicitly reviewed.
function parseSpdx(expr) {
  const tokens = tokenizeSpdx(expr);
  let cursor = 0;

  function primary() {
    const token = tokens[cursor++];
    if (!token) throw new Error('missing license identifier');
    if (token !== '(') return { type: 'license', value: token };
    const node = orExpression();
    if (tokens[cursor++] !== ')') throw new Error('unclosed parenthesis');
    return node;
  }

  function andExpression() {
    let node = primary();
    while (tokens[cursor] === 'AND') {
      cursor += 1;
      node = { type: 'and', left: node, right: primary() };
    }
    return node;
  }

  function orExpression() {
    let node = andExpression();
    while (tokens[cursor] === 'OR') {
      cursor += 1;
      node = { type: 'or', left: node, right: andExpression() };
    }
    return node;
  }

  const tree = orExpression();
  if (cursor !== tokens.length) throw new Error(`unexpected token ${tokens[cursor]}`);
  return tree;
}

function isAllowedChoice(node) {
  if (node.type === 'license') return ALLOWED.has(node.value);
  if (node.type === 'and') return isAllowedChoice(node.left) && isAllowedChoice(node.right);
  return isAllowedChoice(node.left) || isAllowedChoice(node.right);
}

function isUnavoidablyForbidden(node) {
  if (node.type === 'license') return FORBIDDEN.test(node.value);
  if (node.type === 'and')
    return isUnavoidablyForbidden(node.left) || isUnavoidablyForbidden(node.right);
  return isUnavoidablyForbidden(node.left) && isUnavoidablyForbidden(node.right);
}

// An SPDX expression passes when at least one complete license choice fits the policy. Therefore
// "MIT OR GPL-3.0" passes, while "MIT AND GPL-3.0" and "GPL-2.0 OR AGPL-3.0" fail.
export function classifyLicense(expr) {
  if (!expr) return 'unknown';
  try {
    const tree = parseSpdx(expr);
    if (isAllowedChoice(tree)) return 'allowed';
    return isUnavoidablyForbidden(tree) ? 'forbidden' : 'unknown';
  } catch {
    return 'unknown';
  }
}

function renderThirdPartyNotice(packages) {
  const packageNotices = [...packages]
    .filter((pkg) => !pkg.platformSpecific)
    .sort((a, b) => `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`))
    .map((pkg) => {
      const heading = `${pkg.name}@${pkg.version}\nDeclared license: ${pkg.spdx || '(see package)'}\nRegistry: https://www.npmjs.com/package/${pkg.name}`;
      if (!pkg.notices.length) {
        return `${heading}\nNo license or notice file was included at the package root; the declaration above is from package.json.`;
      }
      const texts = pkg.notices.map(({ name, text }) => `--- ${name} ---\n${text}`).join('\n\n');
      return `${heading}\n\n${texts}`;
    });
  return `${NOTICE_HEADER}\n\nNpm package notices\n===================\n\n${packageNotices.join('\n\n')}\n\n${NOTICE_NON_NPM}`;
}

// Walk the dependency graph from the actual top-level links, not every directory left in pnpm's
// content store. A removed package can remain cached under `.pnpm`; listing the store directly
// would put unused software in THIRD-PARTY.txt and could make the gate fail on code that never ships.
const seen = new Map(); // name@version -> package metadata and bundled notice files
const visitedRoots = new Set();

function packageNoticeFiles(root) {
  try {
    return readdirSync(root, { withFileTypes: true })
      .filter(
        (entry) => entry.isFile() && /^(?:licen[cs]e|copying|notice)(?:\.|$)/i.test(entry.name),
      )
      .map((entry) => ({
        name: entry.name,
        text: readFileSync(join(root, entry.name), 'utf8')
          .replaceAll('\r\n', '\n')
          .split('\n')
          .map((line) => line.trimEnd())
          .join('\n')
          .trim(),
      }))
      .filter((notice) => notice.text)
      .sort((a, b) => a.name.localeCompare(b.name));
  } catch {
    return [];
  }
}

function collectPackage(path) {
  let root;
  try {
    root = realpathSync(path);
  } catch {
    return;
  }
  if (visitedRoots.has(root)) return;
  visitedRoots.add(root);
  try {
    const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
    if (pkg.name) {
      const version = pkg.version ?? '0';
      const notices = packageNoticeFiles(root);
      seen.set(`${pkg.name}@${version}`, {
        name: pkg.name,
        version,
        spdx: spdxOf(pkg),
        platformSpecific: Boolean(pkg.os || pkg.cpu || pkg.libc),
        // Packages that ship no license file get their hand-reviewed notice, so the shipped
        // THIRD-PARTY.txt reproduces the real MIT grant instead of a fallback disclaimer.
        notices: notices.length ? notices : (MANUAL_NOTICES.get(`${pkg.name}@${version}`) ?? []),
      });
    }
  } catch {
    return;
  }
  // npm nests dependencies under the package root. pnpm links them beside the package in the
  // package-specific `node_modules` directory; scopes add one extra path segment.
  collectLinks(join(root, 'node_modules'));
  let linkedDependencies = dirname(root);
  if (basename(linkedDependencies).startsWith('@'))
    linkedDependencies = dirname(linkedDependencies);
  if (basename(linkedDependencies) === 'node_modules') collectLinks(linkedDependencies);
}

function collectLinks(dir) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    if (e.name.startsWith('.')) continue;
    const path = join(dir, e.name);
    if (e.name.startsWith('@') && e.isDirectory()) {
      let scoped = [];
      try {
        scoped = readdirSync(path, { withFileTypes: true });
      } catch {
        continue;
      }
      for (const child of scoped) collectPackage(join(path, child.name));
    } else {
      collectPackage(path);
    }
  }
}

export function runLicenseGate({ notice = false } = {}) {
  if (!existsSync(MODULES)) {
    console.error('node_modules not found — run `pnpm install` first.');
    return 1;
  }
  collectLinks(MODULES);

  const forbidden = [];
  const unknown = [];
  for (const { name, spdx } of seen.values()) {
    const verdict = classifyLicense(spdx);
    if (verdict === 'forbidden') forbidden.push([name, spdx || '(none)']);
    else if (verdict === 'unknown') unknown.push([name, spdx || '(none)']);
  }
  forbidden.sort();
  unknown.sort();

  // Manual notices are reviewed per exact version: if the dependency moved and the package still
  // ships no license file, the stale hand-written notice must be re-reviewed, not silently kept.
  const staleManualNotices = [...MANUAL_NOTICES.keys()].filter((key) => {
    if (seen.has(key)) return false;
    const name = key.slice(0, key.lastIndexOf('@'));
    return [...seen.values()].some((pkg) => pkg.name === name);
  });

  console.log(`License gate — scanned ${seen.size} packages.`);

  const mediaFailures = commercialMediaPolicyFailures();
  const speechFailures = commercialSpeechPolicyFailures();
  const thirdPartyNotice = renderThirdPartyNotice(seen.values());

  if (notice) {
    writeFileSync(resolve(ROOT, 'THIRD-PARTY.txt'), thirdPartyNotice);
    console.log('Wrote THIRD-PARTY.txt');
  } else if (readFileSync(resolve(ROOT, 'THIRD-PARTY.txt'), 'utf8') !== thirdPartyNotice) {
    console.error(
      '\n✖ THIRD-PARTY.txt is stale — run `node scripts/check-licenses.mjs --notice` and commit the result.',
    );
    return 1;
  }

  if (staleManualNotices.length) {
    console.error(
      `\n✖ ${staleManualNotices.length} manual notice(s) no longer match the installed version:`,
    );
    for (const key of staleManualNotices) console.error(`    ${key}`);
    console.error(
      '  Re-review the new version (does it ship a license file now?) and update MANUAL_NOTICES.',
    );
    return 1;
  }
  if (forbidden.length) {
    console.error(
      `\n✖ ${forbidden.length} package(s) conflict with the commercial distribution policy:`,
    );
    for (const [n, l] of forbidden) console.error(`    ${n}  —  ${l}`);
    console.error(
      '  Remove, replace, or explicitly review these before shipping a bundled closed-source artifact.',
    );
    return 1;
  }
  if (mediaFailures.length) {
    console.error(`\n✖ ${mediaFailures.length} commercial media policy violation(s):`);
    for (const failure of mediaFailures) console.error(`    ${failure}`);
    console.error(
      '  Remove these fallbacks; generated and bundled media must stay on the reviewed open-codec policy.',
    );
    return 1;
  }
  if (speechFailures.length) {
    console.error(`\n✖ ${speechFailures.length} commercial speech policy violation(s):`);
    for (const failure of speechFailures) console.error(`    ${failure}`);
    console.error('  Restore the reviewed pins, checksums, local boundary, and runtime guidance.');
    return 1;
  }
  if (unknown.length) {
    console.error(`\n✖ ${unknown.length} package(s) have an unrecognized license — classify them:`);
    for (const [n, l] of unknown) console.error(`    ${n}  —  ${l}`);
    console.error(
      '  If policy-compatible, add the SPDX id to ALLOWED (or the package to OVERRIDES) with a note.',
    );
    return 1;
  }
  console.log(
    '✓ Automated dependency, speech, media, codec-selection, and map policy checks passed. Manual rights, patent, service-terms, and release review still apply.',
  );
  return 0;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) process.exitCode = runLicenseGate({ notice: process.argv.includes('--notice') });

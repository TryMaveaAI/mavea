// A few real packages ship an SPDX expression or a missing/odd field that's actually permissive.
// Each entry is a deliberate, reviewed classification — keep this list short and justified.
const OVERRIDES = {
  // The package's bundled LICENSE.md contains the standard MIT grant. Its package.json appends
  // a non-SPDX alternative ("SEE LICENSE IN FEEL-FREE.md"), which the strict parser cannot parse.
  rgbcolor: 'MIT',
};

function spdxOf(pkg) {
  if (OVERRIDES[pkg.name]) return OVERRIDES[pkg.name];
  let l = pkg.license ?? pkg.licenses;
  if (Array.isArray(l))
    l = l
      .map((x) => (typeof x === 'string' ? x : x?.type))
      .filter(Boolean)
      .join(' OR ');
  if (l && typeof l === 'object') l = l.type;
  return typeof l === 'string' ? l.trim() : '';
}

function tokenizeSpdx(expr) {
  const tokens = expr.match(/\(|\)|\bAND\b|\bOR\b|[^\s()]+/gi) ?? [];
  return tokens.map((token) => {
    const upper = token.toUpperCase();
    return upper === 'AND' || upper === 'OR' ? upper : token;
  });
}

// This intentionally supports the part of the SPDX expression grammar used by package.json
// license fields: identifiers, parentheses, AND and OR. WITH exceptions remain a single unknown
// obligation, which is the conservative result until explicitly reviewed.
function parseSpdx(expr) {
  const tokens = tokenizeSpdx(expr);
  let cursor = 0;

  function primary() {
    const token = tokens[cursor++];
    if (!token) throw new Error('missing license identifier');
    if (token !== '(') return { type: 'license', value: token };
    const node = orExpression();
    if (tokens[cursor++] !== ')') throw new Error('unclosed parenthesis');
    return node;
  }

  function andExpression() {
    let node = primary();
    while (tokens[cursor] === 'AND') {
      cursor += 1;
      node = { type: 'and', left: node, right: primary() };
    }
    return node;
  }

  function orExpression() {
    let node = andExpression();
    while (tokens[cursor] === 'OR') {
      cursor += 1;
      node = { type: 'or', left: node, right: andExpression() };
    }
    return node;
  }

  const tree = orExpression();
  if (cursor !== tokens.length) throw new Error(`unexpected token ${tokens[cursor]}`);
  return tree;
}

function isAllowedChoice(node) {
  if (node.type === 'license') return ALLOWED.has(node.value);
  if (node.type === 'and') return isAllowedChoice(node.left) && isAllowedChoice(node.right);
  return isAllowedChoice(node.left) || isAllowedChoice(node.right);
}

function isUnavoidablyForbidden(node) {
  if (node.type === 'license') return FORBIDDEN.test(node.value);
  if (node.type === 'and')
    return isUnavoidablyForbidden(node.left) || isUnavoidablyForbidden(node.right);
  return isUnavoidablyForbidden(node.left) && isUnavoidablyForbidden(node.right);
}

// An SPDX expression passes when at least one complete license choice is resale-safe. Therefore
// "MIT OR GPL-3.0" passes, while "MIT AND GPL-3.0" and "GPL-2.0 OR AGPL-3.0" fail.
export function classifyLicense(expr) {
  if (!expr) return 'unknown';
  try {
    const tree = parseSpdx(expr);
    if (isAllowedChoice(tree)) return 'allowed';
    return isUnavoidablyForbidden(tree) ? 'forbidden' : 'unknown';
  } catch {
    return 'unknown';
  }
}

// Collect real package roots: a package.json whose dir sits directly under a `node_modules/<name>`
// (or `node_modules/@scope/<name>`). We trust the package.json's own name/version, and never
// follow symlinks, so we hit each real package once without chasing the pnpm peer graph in loops.
const seen = new Map(); // name@version -> spdx
function collect(dir) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    if (e.isSymbolicLink()) continue;
    if (!e.isDirectory()) continue;
    const p = join(dir, e.name);
    const pj = join(p, 'package.json');
    if (e.name !== 'node_modules' && existsSync(pj)) {
      try {
        const pkg = JSON.parse(readFileSync(pj, 'utf8'));
        if (pkg.name)
          seen.set(`${pkg.name}@${pkg.version ?? '0'}`, { name: pkg.name, spdx: spdxOf(pkg) });
      } catch {
        /* unreadable package.json — ignored */
      }
    }
    // Recurse into nested node_modules and scope dirs only (keeps the walk bounded).
    if (e.name === 'node_modules' || e.name.startsWith('@')) collect(p);
  }
}

export function runLicenseGate({ notice = false } = {}) {
  if (!existsSync(STORE)) {
    console.error('node_modules/.pnpm not found — run `pnpm install` first.');
    return 1;
  }
  for (const entry of readdirSync(STORE)) {
    collect(join(STORE, entry, 'node_modules'));
  }

  const forbidden = [];
  const unknown = [];
  for (const { name, spdx } of seen.values()) {
    const verdict = classifyLicense(spdx);
    if (verdict === 'forbidden') forbidden.push([name, spdx || '(none)']);
    else if (verdict === 'unknown') unknown.push([name, spdx || '(none)']);
  }
  forbidden.sort();
  unknown.sort();

  console.log(`License gate — scanned ${seen.size} packages.`);

  if (notice) {
    const lines = [...seen.values()].map((p) => `${p.name}\t${p.spdx || '(see package)'}`).sort();
    writeFileSync(
      resolve(ROOT, 'THIRD-PARTY.txt'),
      `${NOTICE_HEADER}\n\n${lines.join('\n')}\n\n${NOTICE_NON_NPM}`,
    );
    console.log('Wrote THIRD-PARTY.txt');
  }

  if (forbidden.length) {
    console.error(
      `\n✖ ${forbidden.length} package(s) carry a license that bars commercial resale:`,
    );
    for (const [n, l] of forbidden) console.error(`    ${n}  —  ${l}`);
    console.error(
      '  Remove or replace these. This gate exists so Mavea can be sold (GPL/AGPL/NC/SSPL etc. cannot).',
    );
    return 1;
  }
  if (unknown.length) {
    console.error(`\n✖ ${unknown.length} package(s) have an unrecognized license — classify them:`);
    for (const [n, l] of unknown) console.error(`    ${n}  —  ${l}`);
    console.error(
      '  If resale-safe, add the SPDX id to ALLOWED (or the package to OVERRIDES) with a note.',
    );
    return 1;
  }
  console.log('✓ All dependencies are free for commercial use and resale.');
  return 0;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) process.exitCode = runLicenseGate({ notice: process.argv.includes('--notice') });

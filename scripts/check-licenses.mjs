/** Objects carrying a remote `url` plus a substantial inline `data` payload are embedded copies. */
export function unreviewedEmbeddedDocs(parsed) {
  const found = [];
  const walk = (node) => {
    if (Array.isArray(node)) {
      for (const item of node) walk(item);
      return;
    }
    if (!node || typeof node !== 'object') return;
    if (
      typeof node.url === 'string' &&
      /^https?:/.test(node.url) &&
      typeof node.data === 'string' &&
      node.data.length > 1024 &&
      !REVIEWED_EMBEDDED_DOCS.has(node.url)
    ) {
      found.push(node.url);
    }
    for (const value of Object.values(node)) walk(value);
  };
  walk(parsed);
  return found;
}

function filesUnder(dir, accept = () => true) {
  const files = [];
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return files;
  }
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...filesUnder(path, accept));
    else if (entry.isFile() && accept(path)) files.push(path);
  }
  return files;
}

/** Media outside the reviewed allowlist and noncommercial service fallbacks fail the same
 *  commercial-use gate as a bad package license. This is intentionally source-level and
 *  fail-closed; it does not claim that automated scanning can provide patent clearance. */
export function commercialMediaPolicyFailures() {
  const failures = [];
  for (const file of filesUnder(resolve(ROOT, 'public'))) {
    if (PUBLIC_MEDIA_EXTENSIONS.test(file)) {
      failures.push(`${file.replace(`${ROOT}/`, '')}: media type outside the reviewed allowlist`);
    }
  }

  for (const file of filesUnder(resolve(ROOT, 'src'), (path) => FIXTURE_EXTENSIONS.test(path))) {
    const text = readFileSync(file, 'utf8');
    const rel = file.replace(`${ROOT}/`, '');
    for (const url of unreviewedHotlinkedMedia(text)) {
      failures.push(`${rel}: unreviewed hotlinked media ${url}`);
    }
    if (file.endsWith('.json')) {
      try {
        for (const url of unreviewedEmbeddedDocs(JSON.parse(text))) {
          failures.push(`${rel}: unreviewed embedded document ${url}`);
        }
      } catch {
        /* not a JSON document — nothing to embed-scan */
      }
    }
  }

  const clipSource = filesUnder(resolve(ROOT, 'src/clip'), (file) => SOURCE_EXTENSIONS.test(file))
    .map((file) => readFileSync(file, 'utf8'))
    .join('\n');
  // The MP4 container is allowed only with the reviewed open codec set. Common patent-pool codecs
  // must never appear in generated-media code, regardless of container.
  const clipRules = [
    [
      /\b(?:avc1?|hevc|hev1|hvc1|aac|h\.?26[45]|x26[45]|mp4a)\b/i,
      'generated-media codec outside the reviewed allowlist',
    ],
    [/\bModelConfig\b|live\/providers|\bgenerateReel\b/, 'hosted or provider-directed Reel path'],
  ];
  for (const [pattern, label] of clipRules) {
    if (pattern.test(clipSource)) failures.push(`src/clip: ${label}`);
  }

  const voiceSource = filesUnder(resolve(ROOT, 'src/voice'), (file) => SOURCE_EXTENSIONS.test(file))
    .map((file) => readFileSync(file, 'utf8'))
    .join('\n');
  if (/response_format\s*:\s*['"](?:mp3|m4a|aac)['"]/i.test(voiceSource)) {
    failures.push('src/voice: audio transport outside the reviewed allowlist');
  }

  const productSource = filesUnder(resolve(ROOT, 'src'), (file) => SOURCE_EXTENSIONS.test(file))
    .map((file) => readFileSync(file, 'utf8'))
    .join('\n');
  if (
    /\b(?:speechSynthesis|SpeechSynthesisUtterance|SpeechRecognition|webkitSpeechRecognition)\b/.test(
      productSource,
    )
  ) {
    failures.push('src: browser-vendor speech service is outside the reviewed local voice stack');
  }

  const localSpeechSources = [
    resolve(ROOT, 'docker-compose.yml'),
    resolve(ROOT, 'voice/whisper.Dockerfile'),
    resolve(ROOT, 'voice/start-whisper.sh'),
  ]
    .filter((file) => existsSync(file))
    .map((file) => readFileSync(file, 'utf8'))
    .join('\n');
  if (localSpeechSources) {
    if (!/ghcr\.io\/remsky\/kokoro-fastapi-cpu:v[\d.]+/.test(localSpeechSources)) {
      failures.push('local speech: approved pinned Kokoro service is missing');
    }
    if (
      !/ggml-org\/whisper\.cpp\/archive\/refs\/tags\/v\$\{WHISPER_CPP_VERSION\}/.test(
        localSpeechSources,
      )
    ) {
      failures.push('local speech: approved pinned whisper.cpp source is missing');
    }
    if (
      !/huggingface\.co\/ggerganov\/whisper\.cpp\/resolve\/\$\{model_revision\}\/ggml-small\.en-q5_1\.bin/.test(
        localSpeechSources,
      )
    ) {
      failures.push('local speech: approved MIT Whisper model is missing');
    }
    const ubuntuPins = localSpeechSources.match(/ubuntu:22\.04@sha256:[a-f0-9]{64}/g);
    if (!ubuntuPins || ubuntuPins.length < 2) {
      failures.push('local speech: Whisper build and runtime bases must use immutable digests');
    }
    for (const pkg of ['build-essential', 'ca-certificates', 'cmake', 'curl', 'libgomp1']) {
      if (!new RegExp(`${pkg}=\\S+`).test(localSpeechSources)) {
        failures.push(`local speech: Ubuntu package ${pkg} is not version-pinned`);
      }
    }
  }

  const mapSources = [
    resolve(ROOT, 'src/canvas/blocks/media/GeoMap.tsx'),
    resolve(ROOT, 'src/canvas/blocks/media/MapRoute.tsx'),
    resolve(ROOT, 'index.html'),
  ]
    .map((file) => readFileSync(file, 'utf8'))
    .join('\n');
  // The negative scan covers ALL product source (a forbidden host anywhere is a violation);
  // index.html rides along inside mapSources, whose CSP allowlist is the load-bearing gate.
  if (/basemaps\.cartocdn\.com|tile\.openstreetmap\.org/i.test(`${productSource}\n${mapSources}`)) {
    failures.push('map rendering: noncommercial/restricted public tile service');
  }
  if (!mapSources.includes('https://tiles.openfreemap.org')) {
    failures.push('map rendering: approved commercial-use tile service is missing');
  }
  return failures;
}


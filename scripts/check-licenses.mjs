const ASSET_CDN_URL =
  /https:\/\/(?:images\.unsplash\.com|images\.pexels\.com|cdn\.pixabay\.com|images-assets\.nasa\.gov|upload\.wikimedia\.org)\/[^\s"'`]+/gi;

/** Remote media URLs in shipped fixture text that lack a reviewed license entry above. */
export function unreviewedHotlinkedMedia(text) {
  const unreviewed = new Set();
  for (const pattern of [HOTLINKED_MEDIA_URL, ASSET_CDN_URL]) {
    for (const [url] of text.matchAll(pattern)) {
      if (url.startsWith('https://example.com/')) continue; // prop-shape placeholder, never fetched
      if (!REVIEWED_HOTLINKED_MEDIA.has(url)) unreviewed.add(url);
    }
  }
  return [...unreviewed];
}


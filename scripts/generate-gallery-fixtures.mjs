#!/usr/bin/env node
// Split complete, shipping examples by renderer family so the public gallery only parses fixtures
// for families that have scrolled near the viewport. The model menu uses separately compacted
// references to save tokens; the gallery must never reuse those shortened strings because that
// would display literal ellipses instead of the real source content and hide layout defects.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TOPIC_LIST } from '../src/data/topics/index.ts';
import { AUTHORED_EXAMPLES } from '../src/live/select/authoredExamples.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const factsSource = readFileSync(
  resolve(ROOT, 'src/canvas/blocks/catalog/facts.generated.ts'),
  'utf8',
);
const examples = {};
for (const topic of TOPIC_LIST) {
  for (const block of topic.blocks) {
    if (block.props && !Object.prototype.hasOwnProperty.call(examples, block.type)) {
      examples[block.type] = block.props;
    }
  }
}
for (const [type, props] of Object.entries(AUTHORED_EXAMPLES)) {
  if (!Object.prototype.hasOwnProperty.call(examples, type)) examples[type] = props;
}
// `composite` is a generative meta-primitive, so it is intentionally absent from the examples
// sent to the model. The gallery still needs one complete, realistic instance to exercise the
// same recursive layout path users can ask Live to compose.
examples.composite = {
  title: 'Launch readiness',
  icon: 'layers',
  regions: [
    {
      block: {
        type: 'kpi',
        id: 'gallery-composite-kpi',
        props: { title: 'Release checks', kpis: [{ val: '12/12', label: 'Passing' }] },
      },
      span: 5,
    },
    {
      block: {
        type: 'list',
        id: 'gallery-composite-list',
        props: { title: 'Next steps', items: ['Ship the candidate', 'Watch real-user metrics'] },
      },
      span: 7,
    },
  ],
  footer: 'The same typed children and layout path used in Live.',
};
const familiesMatch = factsSource.match(/export const FAMILIES = (\[[^;]+\]);/);
const rowsMatch = factsSource.match(/export const FACT_ROWS: FactRow\[\] = (\[[\s\S]+\]);\s*$/);
if (!familiesMatch || !rowsMatch) throw new Error('Could not read generated catalog facts');

const families = JSON.parse(familiesMatch[1]);
const rows = JSON.parse(rowsMatch[1]);
const grouped = Object.fromEntries(families.map((family) => [family, {}]));
for (const row of rows) {
  const [type, familyIndex] = row;
  if (Object.prototype.hasOwnProperty.call(examples, type)) {
    grouped[families[familyIndex]][type] = examples[type];
  }
}

const fixturesDir = resolve(ROOT, 'src/gallery/fixtures');

const loaders = families
  .map(
    (family) =>
      `  ${JSON.stringify(family)}: () => import('./fixtures/${family}.json').then((module) => module.default as GalleryFixtureMap),`,
  )
  .join('\n');
const loaderSource = `// GENERATED by scripts/generate-gallery-fixtures.mjs — DO NOT EDIT BY HAND.\n\nexport type GalleryFixtureMap = Readonly<Record<string, unknown>>;\n\nconst LOADERS: Readonly<Record<string, () => Promise<GalleryFixtureMap>>> = {\n${loaders}\n};\nconst CACHE = new Map<string, Promise<GalleryFixtureMap>>();\n\nexport function loadGalleryFixture(family: string, type: string): Promise<unknown> {\n  const loader = LOADERS[family];\n  if (!loader) return Promise.resolve(undefined);\n  let pending = CACHE.get(family);\n  if (!pending) {\n    pending = loader();\n    CACHE.set(family, pending);\n  }\n  return pending.then((fixtures) => fixtures[type]);\n}\n`;

const outputs = new Map([
  ...families.map((family) => [
    resolve(fixturesDir, `${family}.json`),
    `${JSON.stringify(grouped[family])}\n`,
  ]),
  [resolve(ROOT, 'src/gallery/fixtures.generated.ts'), loaderSource],
]);

if (process.argv.includes('--write')) {
  mkdirSync(fixturesDir, { recursive: true });
  for (const [path, contents] of outputs) writeFileSync(path, contents);
  console.log(`Wrote ${families.length} lazy gallery fixture families.`);
} else {
  const stale = [];
  for (const [path, expected] of outputs) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // Report the missing output with all other stale outputs below.
    }
    if (current !== expected) stale.push(path.slice(ROOT.length + 1));
  }
  if (stale.length) {
    console.error(
      `Gallery fixtures are stale: ${stale.join(', ')}. Run \`pnpm gen:gallery-fixtures\`.`,
    );
    process.exit(1);
  }
  console.log(`✓ ${families.length} lazy gallery fixture families are current.`);
}
